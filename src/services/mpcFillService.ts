/**
 * Extracts matching alter arts from an uploaded/provided MPCFill XML string for a specific card name.
 */
export function extractAltersFromXmlForCard(xmlString: string, targetCardName: string): CardPrint[] {
  try {
    const order = parseMpcFillXml(xmlString);
    const cleanTarget = targetCardName.toLowerCase().replace(/[~`!@#$%^&*(){}\[\];:"'’<,.>?/\\|_+=]/g, '').trim();

    const matches: CardPrint[] = [];
    const allCards = [...order.fronts, ...order.backs];

    for (const c of allCards) {
      const cleanName = c.name.toLowerCase().replace(/[~`!@#$%^&*(){}\[\];:"'’<,.>?/\\|_+=]/g, '').trim();
      const cleanQuery = c.query.toLowerCase().replace(/[~`!@#$%^&*(){}\[\];:"'’<,.>?/\\|_+=]/g, '').trim();

      if (cleanName.includes(cleanTarget) || cleanTarget.includes(cleanName) || cleanQuery === cleanTarget) {
        matches.push({
          id: `mpc-xml-${c.id}`,
          setCode: 'MPC',
          setName: c.alterVariant ? `MPCFill (${c.alterVariant})` : 'MPCFill Alter',
          collectorNumber: '★',
          artist: c.alterVariant || 'MPCFill Community',
          imageUrl: c.imageUrl,
          imageUrlLarge: c.imageUrl,
          imageUrlArtCrop: c.imageUrl,
        });
      }
    }

    return matches;
  } catch {
    return [];
  }
}

export interface MpcSearchOptions {
  minDpi?: number;
  maxDpi?: number;
  cardType?: 'CARD' | 'TOKEN';
  typeLine?: string;
  fuzzySearch?: boolean;
}

export interface MpcCardPrint extends CardPrint {
  dpi?: number;
  sourceName?: string;
  tags?: string[];
  dateCreated?: string;
}

export const CLOUDFLARE_MPC_PROXY = 'https://mpcfill-proxy.anancinho.workers.dev';

export function getProxyBaseUrl(): string {
  if (typeof window !== 'undefined') {
    const envUrl = (import.meta as any).env?.VITE_MPC_PROXY_URL;
    if (envUrl) return envUrl;

    const isLocalhost =
      window.location.hostname === 'localhost' ||
      window.location.hostname === '127.0.0.1';
    if (isLocalhost) {
      return '/api-mpcfill';
    }
  }
  return CLOUDFLARE_MPC_PROXY;
}

// Memory cache for MPCFill sources
let cachedMpcSources: Array<[number, boolean]> | null = null;

/**
 * Queries the MPCFill backend API to search for community alter arts for a card name.
 * Uses the Cloudflare Worker proxy in production (https://mpcfill-proxy.anancinho.workers.dev)
 * and in local development with CORS enabled.
 */
export async function searchMpcFillAlters(
  cardName: string,
  options?: MpcSearchOptions
): Promise<MpcCardPrint[]> {
  try {
    const minDpi = options?.minDpi ?? 200;
    const maxDpi = options?.maxDpi ?? 2400;
    const targetCardType = options?.cardType || 'CARD';

    let cleanQuery = cardName.split('//')[0].trim();

    // If searching for tokens, clean the query from "Token", "Ficha", "1/1", etc.
    if (targetCardType === 'TOKEN') {
      cleanQuery = cleanQuery.replace(/\b(tokens?|ficha[s]?)\b/gi, '').trim();
      cleanQuery = cleanQuery.replace(/\b\d+\/\d+\b/g, '').trim();
      if (!cleanQuery && options?.typeLine) {
        const parts = options.typeLine.split(/[—\-]/);
        if (parts[1]) {
          cleanQuery = parts[1].trim();
        }
      }
    }

    cleanQuery = cleanQuery
      .toLowerCase()
      .replace(/[~`!@#$%^&*(){}\[\];:"'’<,.>?/\\|_+=]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();

    if (!cleanQuery) return [];

    // Base URL: Use configured Cloudflare Worker proxy (CORS-enabled for davimelo.com)
    // or local Vite proxy (/api-mpcfill) when running in local development
    const baseUrl = getProxyBaseUrl();

    // 1. Get sources if not cached
    if (!cachedMpcSources) {
      try {
        const sourcesRes = await fetch(`${baseUrl}/2/sources/`);
        const contentType = sourcesRes.headers.get('content-type') || '';
        if (contentType.includes('text/html')) {
          throw new Error('PROXY_RETURNED_HTML');
        }
        if (sourcesRes.ok) {
          const sourcesData = await sourcesRes.json();
          if (sourcesData && sourcesData.results) {
            cachedMpcSources = Object.values(sourcesData.results).map((s: any) => [s.pk, true]);
          }
        }
      } catch (err: any) {
        if (err?.message === 'PROXY_RETURNED_HTML') {
          throw err;
        }
        // Fallback to synthetic sources array
        cachedMpcSources = Array.from({ length: 300 }, (_, i) => [i + 1, true]);
      }
    }

    // 2. Query editorSearch
    const searchBody = {
      queries: [{ query: cleanQuery, cardType: targetCardType }],
      searchSettings: {
        filterSettings: {
          excludesTags: [],
          includesTags: [],
          languages: ['en'],
          maximumDPI: maxDpi,
          maximumSize: 50,
          minimumDPI: minDpi,
        },
        searchTypeSettings: {
          filterCardbacks: false,
          fuzzySearch: options?.fuzzySearch !== undefined ? options.fuzzySearch : true,
        },
        sourceSettings: { sources: cachedMpcSources || [] },
      },
    };

    const searchRes = await fetch(`${baseUrl}/2/editorSearch/`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(searchBody),
    });

    const contentType = searchRes.headers.get('content-type') || '';
    if (contentType.includes('text/html')) {
      throw new Error('PROXY_RETURNED_HTML');
    }

    if (!searchRes.ok) return [];

    const searchData = await searchRes.json();
    const resultObj =
      searchData?.results?.[cleanQuery] ||
      (searchData?.results ? (Object.values(searchData.results)[0] as any) : undefined);

    const ids: string[] =
      targetCardType === 'TOKEN'
        ? resultObj?.TOKEN || resultObj?.CARD || []
        : resultObj?.CARD || resultObj?.TOKEN || [];
    if (!ids || ids.length === 0) return [];

    // 3. Query card metadata for all matching alter IDs (chunked if very large)
    const chunkSize = 150;
    const cardsMetaMap: Record<string, any> = {};

    for (let i = 0; i < ids.length; i += chunkSize) {
      const chunk = ids.slice(i, i + chunkSize);
      try {
        const metaRes = await fetch(`${baseUrl}/2/cards/`, {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({ cardIdentifiers: chunk }),
        });
        if (metaRes.ok) {
          const metaData = await metaRes.json();
          if (metaData?.results) {
            Object.assign(cardsMetaMap, metaData.results);
          }
        }
      } catch (e) {
        console.warn('Erro ao carregar metadados do lote MPCFill:', e);
      }
    }

    // 4. Transform into CardPrint
    const prints: MpcCardPrint[] = ids.map((id, index) => {
      const meta = cardsMetaMap[id];
      const imageUrl = `https://lh3.googleusercontent.com/d/${id}`;
      const dpiNum = meta?.dpi ? Number(meta.dpi) : undefined;
      return {
        id: `mpc-alter-${id}`,
        setCode: 'MPC',
        setName: meta?.name || `MPCFill Alter #${index + 1}`,
        collectorNumber: dpiNum ? `${dpiNum} DPI` : '★',
        artist: meta?.sourceName || meta?.source || 'Comunidade MPCFill',
        imageUrl,
        imageUrlLarge: imageUrl,
        imageUrlArtCrop: imageUrl,
        releasedAt: meta?.dateCreated || undefined,
        dpi: dpiNum,
        sourceName: meta?.sourceName || meta?.source || 'Comunidade MPCFill',
        tags: meta?.tags || [],
        dateCreated: meta?.dateCreated,
      };
    });

    // Filter by minDpi if specified
    const filteredPrints = prints.filter((p) => {
      if (p.dpi !== undefined) {
        return p.dpi >= minDpi;
      }
      return true;
    });

    // Default sort by highest DPI first
    filteredPrints.sort((a, b) => (b.dpi || 0) - (a.dpi || 0));

    return filteredPrints;
  } catch (err: any) {
    if (err?.message === 'PROXY_RETURNED_HTML' || err?.message === 'VITE_PROXY_NOT_ACTIVE') {
      console.warn('Proxy MPCFill retornou HTML ou não está ativo.');
      throw err;
    }
    console.warn('Erro ao consultar MPCFill API:', err);
    return [];
  }
}


