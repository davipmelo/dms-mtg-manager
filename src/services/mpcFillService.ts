import { Card, ProxyItem, Deck, DeckCard, CardPrint } from '../types';

export interface MpcFillParsedCard {
  id: string; // Google Drive ID
  rawName: string; // e.g. "Goblin Chieftain (Sam Wood) [M10] {139}.png"
  name: string; // Cleaned base name, e.g. "Goblin Chieftain"
  alterVariant?: string; // e.g. "(Sam Wood) [M10] {139}"
  query: string; // Raw query string, e.g. "goblin chieftain"
  slots: number[]; // Target slot index(es)
  imageUrl: string; // https://lh3.googleusercontent.com/d/{id}
}

export interface MpcFillOrder {
  fileName?: string;
  details: {
    quantity: number;
    bracket?: number;
    stock?: string;
    foil?: boolean;
  };
  fronts: MpcFillParsedCard[];
  backs: MpcFillParsedCard[];
  cardbackId?: string; // Optional default cardback image/drive ID
}

/**
 * Parses slot notation from MPCFill XML:
 * Examples: "<slots>0</slots>", "<slot>1</slot>", "<slots>[2, 3]</slots>", "<slots>4, 5</slots>"
 */
export function parseMpcSlots(str: string): number[] {
  if (!str) return [];
  const cleaned = str.replace(/[\[\]]/g, ' ');
  return cleaned
    .split(/[,\s]+/)
    .map((s) => parseInt(s.trim(), 10))
    .filter((n) => !isNaN(n));
}

/**
 * Cleans the raw filename and query into a recognizable MTG card name and alter variant tag.
 */
export function parseMpcCardNames(
  rawName: string,
  rawQuery?: string
): { baseName: string; extraInfo: string; withoutExt: string } {
  const withoutExt = rawName ? rawName.replace(/\.(png|jpg|jpeg|webp)$/i, '').trim() : '';

  // Separate base card name before first delimiter '(', '[', or '{'
  const match = withoutExt.match(/^([^([{\t]+)(?:[\s]*([([{].*))?$/);
  let baseName = '';
  let extraInfo = '';

  if (match) {
    baseName = match[1].trim();
    extraInfo = (match[2] || '').trim();
  } else {
    baseName = withoutExt;
  }

  // Fallback to title-casing query if baseName is empty
  if (!baseName && rawQuery) {
    baseName = rawQuery
      .trim()
      .replace(/\b\w/g, (char) => char.toUpperCase());
  }

  return {
    baseName: baseName || 'Carta Customizada',
    extraInfo,
    withoutExt,
  };
}

/**
 * Parses an MPCFill XML document (either generated by MPCFill.com or mpc-autofill).
 */
export function parseMpcFillXml(xmlString: string, fileName?: string): MpcFillOrder {
  if (!xmlString || typeof xmlString !== 'string') {
    throw new Error('Conteúdo do arquivo XML inválido ou vazio.');
  }

  const quantityMatch = xmlString.match(/<quantity>(\d+)<\/quantity>/i);
  const bracketMatch = xmlString.match(/<bracket>(\d+)<\/bracket>/i);
  const stockMatch = xmlString.match(/<stock>(.*?)<\/stock>/i);
  const foilMatch = xmlString.match(/<foil>(.*?)<\/foil>/i);
  const cardbackMatch = xmlString.match(/<cardback>(.*?)<\/cardback>/i);

  const frontsMatch = xmlString.match(/<fronts>([\s\S]*?)<\/fronts>/i);
  const backsMatch = xmlString.match(/<backs>([\s\S]*?)<\/backs>/i);

  function extractCards(sectionContent: string): MpcFillParsedCard[] {
    if (!sectionContent) return [];
    const cardMatches = [...sectionContent.matchAll(/<card>([\s\S]*?)<\/card>/gi)];

    return cardMatches.map((cm) => {
      const cardStr = cm[1];
      const id = (cardStr.match(/<id>(.*?)<\/id>/i) || [])[1]?.trim() || '';
      const name = (cardStr.match(/<name>(.*?)<\/name>/i) || [])[1]?.trim() || '';
      const query = (cardStr.match(/<query>(.*?)<\/query>/i) || [])[1]?.trim() || '';
      const slotsStr = (cardStr.match(/<slots?>(.*?)<\/slots?>/i) || [])[1]?.trim() || '';
      const slots = parseMpcSlots(slotsStr);
      const { baseName, extraInfo, withoutExt } = parseMpcCardNames(name, query);

      return {
        id,
        rawName: name,
        name: baseName,
        alterVariant: extraInfo || withoutExt,
        query,
        slots,
        imageUrl: id ? `https://lh3.googleusercontent.com/d/${id}` : '',
      };
    });
  }

  const fronts = frontsMatch ? extractCards(frontsMatch[1]) : [];
  const backs = backsMatch ? extractCards(backsMatch[1]) : [];

  if (fronts.length === 0) {
    throw new Error(
      'Nenhuma carta foi encontrada no bloco <fronts> do XML. Verifique se o arquivo é um XML válido gerado pelo MPCFill.'
    );
  }

  return {
    fileName,
    details: {
      quantity: quantityMatch ? parseInt(quantityMatch[1], 10) : fronts.length,
      bracket: bracketMatch ? parseInt(bracketMatch[1], 10) : undefined,
      stock: stockMatch ? stockMatch[1].trim() : undefined,
      foil: foilMatch ? foilMatch[1].trim().toLowerCase() === 'true' : false,
    },
    fronts,
    backs,
    cardbackId: cardbackMatch ? cardbackMatch[1].trim() : undefined,
  };
}

export interface BuildProxyOptions {
  includeDefaultBack?: boolean;
}

/**
 * Transforms an MPCFill order into ready-to-print ProxyItems.
 * Supports:
 * - Double-sided cards (front face immediately followed by matching back face)
 * - Grouping of adjacent identical cards
 * - High-resolution Google Drive CDN images with CORS enabled
 */
export function buildProxyItemsFromMpcOrder(
  order: MpcFillOrder,
  options: BuildProxyOptions = {}
): ProxyItem[] {
  // Map backs by slot index
  const backsBySlot = new Map<number, MpcFillParsedCard>();
  for (const back of order.backs) {
    for (const slot of back.slots) {
      backsBySlot.set(slot, back);
    }
  }

  // Expand front cards by slot
  const slotEntries: Array<{ slot: number; front: MpcFillParsedCard }> = [];
  let fallbackSlot = 0;

  for (const front of order.fronts) {
    const slots = front.slots.length > 0 ? front.slots : [fallbackSlot++];
    for (const slot of slots) {
      slotEntries.push({ slot, front });
    }
  }

  // Sort by slot index ascending
  slotEntries.sort((a, b) => a.slot - b.slot);

  const proxyItems: ProxyItem[] = [];
  const timestamp = Date.now();
  let itemIndex = 0;

  for (let i = 0; i < slotEntries.length; i++) {
    const { slot, front } = slotEntries[i];
    const matchingBack = backsBySlot.get(slot);
    const hasBack = Boolean(matchingBack);

    // Front card instance
    const frontCard: Card = {
      id: `mpc-${front.id}-${slot}-front`,
      name: front.name,
      cmc: 0,
      typeLine: front.alterVariant ? `Proxy Alter • ${front.alterVariant}` : 'Proxy Alter MPCFill',
      oracleText: 'Arte customizada importada do MPCFill.com',
      colors: [],
      colorIdentity: [],
      rarity: 'special',
      setName: front.alterVariant ? `MPCFill (${front.alterVariant})` : 'MPCFill Alter',
      setCode: 'MPC',
      collectorNumber: String(slot + 1),
      imageUrl: front.imageUrl,
      imageUrlLarge: front.imageUrl,
      faceLabel: hasBack ? 'frente' : undefined,
    };

    // Check if we can group with the immediately previous item (identical front and back)
    const prevItem = proxyItems[proxyItems.length - 1];
    const prevMatchingBack = slotEntries[i - 1] ? backsBySlot.get(slotEntries[i - 1].slot) : undefined;
    const canGroupWithPrev =
      !hasBack &&
      !options.includeDefaultBack &&
      prevItem &&
      prevItem.card.imageUrl === front.imageUrl &&
      prevItem.card.name === front.name &&
      !prevMatchingBack;

    if (canGroupWithPrev) {
      prevItem.quantity += 1;
      continue;
    }

    // Add front card
    proxyItems.push({
      id: `proxy-mpc-${timestamp}-${itemIndex++}-${slot}`,
      card: frontCard,
      quantity: 1,
    });

    // If double-sided card with custom back, add back card immediately after
    if (matchingBack) {
      const backCard: Card = {
        id: `mpc-${matchingBack.id}-${slot}-back`,
        name: `${matchingBack.name} (Verso)`,
        cmc: 0,
        typeLine: matchingBack.alterVariant
          ? `Proxy Alter (Verso) • ${matchingBack.alterVariant}`
          : 'Proxy Alter MPCFill (Verso)',
        oracleText: 'Verso customizado importado do MPCFill.com',
        colors: [],
        colorIdentity: [],
        rarity: 'special',
        setName: matchingBack.alterVariant ? `MPCFill (${matchingBack.alterVariant})` : 'MPCFill Alter',
        setCode: 'MPC',
        collectorNumber: String(slot + 1),
        imageUrl: matchingBack.imageUrl,
        imageUrlLarge: matchingBack.imageUrl,
        faceLabel: 'verso',
      };

      proxyItems.push({
        id: `proxy-mpc-${timestamp}-${itemIndex++}-${slot}-back`,
        card: backCard,
        quantity: 1,
      });
    } else if (options.includeDefaultBack && order.cardbackId) {
      // Optional default cardback
      const defaultBackCard: Card = {
        id: `mpc-cardback-${timestamp}-${slot}`,
        name: 'Verso Padrão (MTG Sleeve)',
        cmc: 0,
        typeLine: 'Verso de Carta MTG',
        oracleText: 'Verso padrão de sleeve / fundo de carta.',
        colors: [],
        colorIdentity: [],
        rarity: 'common',
        setName: 'MPCFill Cardback',
        setCode: 'MPC',
        collectorNumber: String(slot + 1),
        imageUrl: `https://lh3.googleusercontent.com/d/${order.cardbackId}`,
        imageUrlLarge: `https://lh3.googleusercontent.com/d/${order.cardbackId}`,
        faceLabel: 'verso',
      };

      proxyItems.push({
        id: `proxy-mpc-${timestamp}-${itemIndex++}-${slot}-cardback`,
        card: defaultBackCard,
        quantity: 1,
      });
    }
  }

  return proxyItems;
}

/**
 * Converts an MPCFill order into a Deck structure.
 */
export function buildDeckFromMpcOrder(order: MpcFillOrder, customName?: string): Deck {
  const proxyItems = buildProxyItemsFromMpcOrder(order);

  // Group by card image or name for deck list
  const deckCardsMap = new Map<string, { card: Card; quantity: number }>();

  for (const item of proxyItems) {
    const key = item.card.name;
    const existing = deckCardsMap.get(key);
    if (existing) {
      existing.quantity += item.quantity;
    } else {
      deckCardsMap.set(key, { card: item.card as Card, quantity: item.quantity });
    }
  }

  const cards: DeckCard[] = Array.from(deckCardsMap.values()).map((entry) => ({
    card: entry.card,
    quantity: entry.quantity,
    category: 'main',
  }));

  // Clean deck name
  let name = customName?.trim();
  if (!name && order.fileName) {
    name = order.fileName.replace(/\.xml$/i, '').replace(/[_-]+/g, ' ').trim();
    name = name.replace(/\b\w/g, (c) => c.toUpperCase());
  }
  if (!name) name = 'Deck MPCFill Importado';

  // Identify potential commander (e.g. if single legendary or if matches deck name)
  let commanderCard: Card | undefined;
  const lowerName = name.toLowerCase();
  for (const dc of cards) {
    if (lowerName.includes(dc.card.name.toLowerCase())) {
      commanderCard = dc.card;
      dc.category = 'commander';
      break;
    }
  }

  // Cover image from commander or first card
  const coverImageUrl = commanderCard?.imageUrl || cards[0]?.card?.imageUrl;

  const deckId = `deck-mpc-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`;
  const now = new Date().toISOString();

  return {
    id: deckId,
    name,
    format: 'commander',
    description: `Deck importado de arquivo XML do MPCFill (${cards.reduce((s, c) => s + c.quantity, 0)} cartas).`,
    commanderCard,
    cards,
    coverImageUrl,
    createdAt: now,
    updatedAt: now,
    tags: ['mpcfill', 'alters', 'proxy'],
  };
}

/**
 * Extracts Google Drive ID from raw ID, sharing link, or uc?id link.
 */
export function extractGoogleDriveId(input: string): string | null {
  if (!input) return null;
  const trimmed = input.trim();
  const fileDMatch = trimmed.match(/\/d\/([a-zA-Z0-9_\-]+)/);
  if (fileDMatch) return fileDMatch[1];
  const idParamMatch = trimmed.match(/[?&]id=([a-zA-Z0-9_\-]+)/);
  if (idParamMatch) return idParamMatch[1];
  if (/^[a-zA-Z0-9_\-]{20,50}$/.test(trimmed)) {
    return trimmed;
  }
  return null;
}

/**
 * Creates a CardPrint instance from a Google Drive ID or MPCFill alter.
 */
export function createPrintFromMpcId(
  cardName: string,
  driveIdOrUrl: string,
  title?: string,
  artist?: string
): CardPrint | null {
  const driveId = extractGoogleDriveId(driveIdOrUrl);
  if (!driveId) return null;

  const imageUrl = `https://lh3.googleusercontent.com/d/${driveId}`;
  return {
    id: `mpc-alter-${driveId}`,
    setCode: 'MPC',
    setName: title || 'MPCFill Alter',
    collectorNumber: '★',
    artist: artist || 'Comunidade MPCFill',
    imageUrl,
    imageUrlLarge: imageUrl,
    imageUrlArtCrop: imageUrl,
  };
}

